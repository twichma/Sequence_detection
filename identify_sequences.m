%% read event data
function data = read_event_file(fname)
% This is a helper function used to read data generated by the Inscopix
% routine that produces deconvoluted ('spike') data from calcium imaging
% traces.  fname is the name of the Inscopix data file (this is a csv 
% file).

% read original data
B = table2struct(readtable(fname));     % read input file into structure

% transfer variables from the unwieldy structure B to more convenient
% variables timeB, valueB and chanB.  An event in chanB(i) at timeB(i) has
% an amplitude of valueB(i).
timeB = NaN(size(B,1),1);
valueB = timeB;
chanB = timeB;
for i = 1:size(B,1)
    timeB(i) = B(i).Time_s_;
    valueB(i) = B(i).Value;
    chanB(i) = str2num(B(i).CellName(2:end));
end

% sort them and generate output structure
UniqueCellNumbers = unique(chanB);          % identify unique entries into chanB                        
num_cells = length(UniqueCellNumbers);      % convenience value, measuring the number of cells in input array
for i = 1:num_cells                         % for all cells ...
    data(i).chan = UniqueCellNumbers(i);    % generate a look-up table, data(i).chan contains cell numbers in the original data array
    data(i).time = timeB(chanB == data(i).chan);    % data(i).time contains the corresponding timeB 
    data(i).value = valueB(chanB == data(i).chan);  % data(i).value contains the corresponding amplitude values
end

end

%% remove double counted entries
function NDC = eliminate_double_counting_v2(T,S,DA,num_rep)
% This routine identifies event sequences that are entirely contained in 
% other identified sequences (for example a two step sequence [e.g., 2 5], with 
% each member of that sequence being also part of a three step sequence 
% [e.g., 7 2 5]).  The shorter of such double-counted sequences is removed.
% If a short sequence is partly overlapping with a longer one, but can also 
% occur independently, the function re-checks whether the independent
% occurrences occur often enough to qualify for a standalone sequence
% designation.
%
% Command line parameters:
%
% T: times of sequence occurrences (in s) 
%
% S: array of sequences (zero-padded)
% 
% DA: input data array (as a string of 1s and 0s) for each channel,
% denoting ms steps
%
% num_rep: minimal number a given sequence must be replicated 

% determine length of sequences and generate processing order (descending length of sequences)
len = zeros(size(T,2),1);
for i = 1:size(T,2)
    len(i) = find([S(i,:) 0] ~= 0,1,'last');    % find the last non-zero entry
end
[~,ind] = sort(len,'descend');                  % sort sequences by length (ind is the sequence of index entries in the S (or T) array)

% re-generate ind, to be in order of the length of the sequence, and, within
% a given length, in order of the number of repetitions
so = zeros(size(len));                          % sort order vector
j = 0;                                          % running index within sort order vector
for i = max(len):-1:2                           % go backward through the lengths of len (starting with the max)    
    h = find(len(ind) == i);                    % find the entries in the len(ind) vector that have the length i     
    len1 = zeros(length(h),1);                  % helper variable
    for k = 1:length(h)                         % for each of the entries (k) within len(ind) that have the length i ...
        len1(k) = size(T{ind(h(k))},1);         % set len1(k) to the corresponding number of repetitions of the sequence
    end
    [~,ind2] = sort(len1,'descend');            % ind2 is the sort order within len1 of the sequences by descending numbers of repetitions
    so(j+1:j+length(h)) = h(ind2);              % add elements to the sort order vector in the order of sequence repetitions
    j = j+length(h);                            % update the running index within the sort order vector
end
ind = ind(so);                                  % update the order within ind (note that the actual number within ind are still referring to indices within T and S).

if ~isempty(ind)
    for i = 1:length(ind)          % for all sequences in descending order of length and recurrence rates ...
        for j = 1:len(ind(i))      % for all individual member of the sequence ...    
            valid_time = ones(size(T{ind(i)}(:,j),1),1);                    % helper variable that refers to recurrence times within T
            if ~isempty(T{ind(i)}(:,j))                                     % should never be empty, but just in case ...    
                for k = 1:size(T{ind(i)}(:,j),1)                            % for all entries into the relevant T entry
                    % the following steps will identify events that are part of
                    % sequences to '2' and label times that are already identified as part of a
                    % longer sequences as invalid (valid_time is set to 0
                    % for such events)
                    try    
                    if DA(S(ind(i),j),round(T{ind(i)}(k,j)*1000)) == 2
                        valid_time(k) = 0;
                    else
                        DA(S(ind(i),j),round(T{ind(i)}(k,j)*1000)) = 2;
                    end
                    catch
                    end
                end
            end
            T{ind(i)} = T{ind(i)}(valid_time == 1,:);       % we keep only those time entries that are valid
        end
    end
end

% final generation of output. NDC.S are sequences, NDC.T are corresponding
% occurrences
j = 0;
NDC.S = [];
NDC.T = struct([]);
% the following step tests whether the valid sequences occur often enough
% to be counted (if their number is greater than num_rep)
if ~isempty(S)
    for i = 1:size(S,1)
        if size(T{i},1) >= num_rep  % if there are sufficient occurrences of the sequence ...
            j = j+1;                % increment the sequence counter
            NDC.S(j,:) = S(i,:);    % assign the sequence to NDC.S
            NDC.T{j} = T{i};        % assign the sequence occurrences to NDC
        end
    end
end

end

%% calculate sequence index 2 
function I = calculate_sequence_index_2(Q)
% This function generates statistics on the proportion of spikes of
% individual cells that were engaged in sequences (either on a per-cell
% basis, across cells, or as a global parameter for all spikes of that
% recording.

nsis = zeros(size(Q.data.converted_array,1),1);             % a vector where each entry represents one cell 
num_events = nsis;                                          % another vector of the same size as nsis   
for i = 1:size(Q.sequences,1)                               % for all identified sequence entries (which are in the form of an array that is padded with zeros)
    h = find([Q.sequences(i,:) 0] ~= 0,1,'last');           % find the true sequence length 
    for j = 1:h                                             % for all members of the sequence
       nsis(Q.sequences(i,j)) = nsis(Q.sequences(i,j)) + size(Q.sequence_times{i},1);   % for each cell identify in how many repetitions of sequences it was involved
    end
end
for i = 1:length(num_events)                                % for all cells ...
    num_events(i) = size(Q.data.original(i).time,1);        % log the total number of events that were identified
end
I.individual_cells.proportion = nsis ./ num_events;         % I.individual_cells is the proportion of events of a given cell that were part of sequences
I.individual_cells.average = mean(I.individual_cells.proportion);      % Average proportion of events of a given cell that were part of sequences
I.individual_cells.SD = std(I.individual_cells.proportion);            % SD of proportion of events of a given cell that were part of sequences
I.individual_cells.median = median(I.individual_cells.proportion);     % median proportion of events of a given cell that were part of sequences
I.individual_cells.iqr = iqr(I.individual_cells.proportion);           % inter-quartile range of proportion of events of a given cell that were part of sequences
I.global = sum(nsis)/sum(num_events);                       % I.global is the a global parameter, describing how many spikes (out of all spikes) were involved in sequences

end