%% function to find 2-step patterns
function ST = find_pattern_2_v2(D,P,t,sep,X)
% This function checks whether and how often a specific pattern P occurs
% in the data array D, using the time window t and the shortest 
% separation parameter sep.  Command line parameters:
%
% D: data array (cells x time (in ms))
%
% P: test pattern (e.g. [1 2] means that cell activity 1 is followed by 
% cell activity 2)
%
% t:time window of occurrence (e.g., [0.05 2] means that the separation 
% between events that are members of the sequence is between 50 ms and 
% 2s.
%
% sep: minimal separation between sequences (in s)

% convert t and sep into ms values
t = round(t*1000);              
sep = sep*1000;

% find pattern occurrences
hit1 = X(D(P(1),1:length(D(P(1),:))-t(2)) == 1);            % identify all occurrences of the first member of the pattern (P(1)) within the corresponding data stream (D(P(1),:)) that may qualify.  t(2) is subtracted because no event can qualify that does not leave room for t(2) milliseconds until the end of the record
sequence_time = NaN(length(hit1),2);                        % initialize sequence_time array (NaNs) - each row of the array will contain one hit1 entry, and a corresponding second event (if any)
sequence_time(:,1) = hit1;                                  % populate the first member of each row with hit 1 (note - hit1 is an index in the data array D. Because D is a series of 1s and 0s with 1ms separation, the indices correspond to times (in ms))
for i = 1:length(hit1)                                      % for all hit1 values ...
    hit2 = X(D(P(2),hit1(i)+t(1):hit1(i)+t(2)));
    if hit2                                                 % if something was found ...
        sequence_time(i,2) = hit1(i)+t(1)-1 + hit2(end);    % populate the second member of the sequence_time array
    end
end
sequence_time = sequence_time(~isnan(sequence_time(:,2)),:);    % restrict the sequence_time array to only those entries where both entries were valid

ST = [];                                                    % ST is the output structure, containing the timing of the times the sequence in question was identified
if ~isempty(sequence_time)                                  % if there are any entries ...
    ST = [sequence_time(1,:); sequence_time];               % an array is generated that contains the first line twice (so that we can utilize the diff function in the next step)
    ST = [sequence_time(1,:); sequence_time(diff(ST(:,1)) >= sep,:)];   % calculate time difference between successive occurrences of the sequence (diff(ST(:,1)), and make sure that they are at least sep ms apart
end

ST = ST/1000;                                               % convert ST into seconds

end

%% Calculate centiles
function p = centile_value(v,A)
% this generates centile values (actually fractions, to reduce the
% computational load (e.g., 0.67 corresponds to 67%)

p = (sum(A < v) + 0.5*sum(A == v)) / length(A);
end

%% Shuffle data
function D_s = shuffle_data(D)
% This function generates shuffled data, using a circshift mechanism (by a
% random number of positions within the original data.  All rows of
% input array D are circ-shifted by a random number of positions

D_s = false(size(D));
for j = 1:size(D,1)
        D_s(j,:) = circshift(D(j,:),randi(length(D(j,:))));
end

