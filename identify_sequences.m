%% function to find 3-step patterns
function ST = find_pattern_3(D,P,t,sep,X)
% This function checks whether and how often a specific pattern P occurs
% in the data array D, using the time window t and the shortest 
% separation parameter sep.  Command line parameters:
%
% D: data array (cells x time (in ms))
%
% P: test pattern (e.g. [1 2 4] means that cell activity 1 is followed by 
% cell activity 2, and then 4)
%
% t:time window of occurrence (e.g., [0.05 2] means that the separation 
% between events that are members of the sequence is between 50 ms and 
% 2s.
%
% sep: minimal separation between sequences (in s)

% convert t and sep into ms values
t = round(t*1000);
sep = sep*1000;

m = 0;
hit1 = X(D(P(1),1:length(D(P(1),:))-2*t(2)-2));                                 % identify all occurrences of the first member of the pattern (P(1)) within the corresponding data stream (D(P(1),:)) that may qualify.  t(2)*2-2 is subtracted because no event can qualify that does not leave room for t(2)*2-2 milliseconds until the end of the record
sequence_time = NaN(length(hit1),3);                                            % initialize sequence_time array (NaNs) - each row of the array will contain one hit1 entry, and corresponding second and third events (if any)

for i = 1:length(hit1)                                                          % for all hit1 values ...
    hit2 = X(D(P(2),hit1(i)+t(1):hit1(i)+t(2)));                                % check whether there the second member of the sequence pattern (P(2)) is present in the window between t(1) and t(2) after that event.  Pick the last of these events, and determine the actual time within the record (add hit1(i)+t(1))
    if ~isempty(hit2)                                                           % if there were any hit2 values ...
        for j = 1:length(hit2)                                                  % for all hit2 values
            hit2(j) = hit2(j) + hit1(i) + t(1) - 1;                             % correct the hit2 values 
            hit3 = X(D(P(3),hit2(j) + t(1):hit2(j) + t(2)));                    % check whether there the third member of the sequence pattern (P(3)) is present in the window between t(1) and t(2) after that event.  Pick the last of these events, and determine the actual time within the record (add hit2(i)+t(1))
            if ~isempty(hit3)                                                   % if there was a hit3 event ...
                hit3 = hit3(end) + hit2(j) + t(1) - 1;                          % correct the timing
                m = m+1;                                                        % increment counter of valid sequences    
                sequence_time(m,:) = [hit1(i) hit2(j) hit3];                    % populate the sequence_time array with the identified values
                break;                                                          % avoids adding multiple instances of a sequence starting from the same root (hit1)
            end
        end
    end
end

ST = [];                                                        % ST is the output structure, containing the timing of the times the sequence in question was identified
if m > 0                                                        % if three step sequences were found ...
    ST = NaN(m,3);                                              % ST is re-initialized to an NaN array    
    n = 1;                                                      % valid sequence counter
    ST(1,:) = sequence_time(1,:);                               % the first entry in the array will always be the first occurrence of the sequence    
    for i = 2:m
        if sequence_time(i,1)-sequence_time(i-1,1) >= sep       % if subsequent entries of sequence_time are sufficiently separated from one another ...
            n = n+1;                                            % increment valid sequence counter
            ST(n,:) = sequence_time(i,:);                       % and populate output array
        end
    end
    ST = ST(1:n,:);                                             % restrict output array to only those entries that are valid (1:n)
end

ST = ST/1000;                                                   % convert ST to seconds

end

